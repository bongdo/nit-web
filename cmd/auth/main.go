package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"nitgui/internal/auth"
)

func main() {
	defaultPath := ""
	if dir, err := os.UserConfigDir(); err == nil {
		defaultPath = filepath.Join(dir, "nit-gui", "auth.env")
	}
	out := flag.String("out", defaultPath, "path to the auth env file")
	force := flag.Bool("force", false, "overwrite an existing auth env file")
	password := flag.String("password", "", "use this password instead of generating one")
	flag.Parse()

	if *out == "" {
		fmt.Fprintln(os.Stderr, "auth: cannot determine config directory; pass -out")
		os.Exit(1)
	}
	if !*force {
		if _, err := os.Stat(*out); err == nil {
			fmt.Fprintf(os.Stderr, "auth: %s already exists; pass -force to rotate\n", *out)
			os.Exit(1)
		}
	}
	if *password == "" {
		generated, err := auth.Generate(24)
		if err != nil {
			fmt.Fprintf(os.Stderr, "auth: generate password: %v\n", err)
			os.Exit(1)
		}
		*password = generated
	}
	hash, err := auth.Hash(*password)
	if err != nil {
		fmt.Fprintf(os.Stderr, "auth: hash password: %v\n", err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(*out), 0o700); err != nil {
		fmt.Fprintf(os.Stderr, "auth: create config directory: %v\n", err)
		os.Exit(1)
	}
	body := strings.Join([]string{
		"# Generated by bin/auth. Keep this file private.",
		"NIT_GATE_PASSWORD_HASH='" + hash + "'",
		"",
	}, "\n")
	if err := os.WriteFile(*out, []byte(body), 0o600); err != nil {
		fmt.Fprintf(os.Stderr, "auth: write %s: %v\n", *out, err)
		os.Exit(1)
	}
	_ = os.Chmod(*out, 0o600)
	fmt.Printf("password: %s\n", *password)
	fmt.Printf("env: %s\n", *out)
	fmt.Fprintln(os.Stderr, "auth: store the password now; only the hash is saved")
}
